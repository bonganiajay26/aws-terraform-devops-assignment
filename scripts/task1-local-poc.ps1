<#
.SYNOPSIS
    Task 1 LOCAL POC - proves the multi-instance EC2 design without an AWS account.
.DESCRIPTION
    1. Baseline      : scripts/validate-local.ps1 (fmt, init, validate, hygiene)
    2. Anti-pattern  : `prevent_destroy = each.value.protected` is rejected by Terraform
    3. Offline plan  : account-a planned with MOCK credentials and all AWS API calls
                       skipped (temporary git-ignored offline_override.tf); asserts
                       5 instances, types, volumes, IOPS, key pairs, tags, protection
                       and output keys from the plan JSON
    4. Negative input: every tests/fixtures/task1/*.vars.hcl must be rejected with
                       its expected validation message
    5. prevent_destroy mechanism demo (terraform_data, local state in TEMP):
                       unprotected removal plans a destroy; protected removal and
                       `terraform destroy` both fail with "Instance cannot be destroyed"

    What this does NOT prove (REAL AWS POC, tests/task1-test.md): that AWS accepts
    the AMI / key pairs / subnet, that instances launch, real IDs/IPs, and
    prevent_destroy against real EC2 state.
.EXAMPLE
    powershell -ExecutionPolicy Bypass -File .\scripts\task1-local-poc.ps1
#>
[CmdletBinding()]
param()

$ErrorActionPreference = 'Continue'
$repoRoot = Split-Path -Parent $PSScriptRoot
$stackDir = Join-Path $repoRoot 'account-a'
$overridePath = Join-Path $stackDir 'offline_override.tf'
$results = [ordered]@{}

function Write-Step {
    param([string]$Message)
    Write-Host ''
    Write-Host "==> $Message" -ForegroundColor Cyan
}

function Write-Check {
    param([string]$Name, [bool]$Passed, [string]$Detail = '')
    $label = 'FAIL'
    $color = 'Red'
    if ($Passed) {
        $label = 'ok  '
        $color = 'Green'
    }
    Write-Host ("  [{0}] {1} {2}" -f $label, $Name, $Detail) -ForegroundColor $color
    return $Passed
}

function Invoke-Terraform {
    # Runs terraform, returns @{ Exit = <int>; Text = <combined stdout+stderr> }.
    param([string[]]$Arguments)
    $text = (& terraform @Arguments *>&1 | Out-String)
    return @{ Exit = $LASTEXITCODE; Text = $text }
}

# Expected result of terraform.tfvars.example (the test oracle).
$expected = [ordered]@{
    web01 = @{ Type = 't3.micro'; Vol = 'gp3'; Size = 20; Iops = $null; Tp = $null; Key = 'web01-key'; Env = 'dev'; Protected = $false }
    web02 = @{ Type = 't3.small'; Vol = 'gp2'; Size = 30; Iops = $null; Tp = $null; Key = 'web02-key'; Env = 'dev'; Protected = $false }
    web03 = @{ Type = 't3.medium'; Vol = 'io2'; Size = 50; Iops = 3000; Tp = $null; Key = 'web03-key'; Env = 'prod'; Protected = $true }
    web04 = @{ Type = 't3.large'; Vol = 'gp3'; Size = 80; Iops = 6000; Tp = 250; Key = 'web04-key'; Env = 'dev'; Protected = $false }
    web05 = @{ Type = 't3.xlarge'; Vol = 'io1'; Size = 100; Iops = 4000; Tp = $null; Key = 'web05-key'; Env = 'dev'; Protected = $false }
}
$expectedOwner = 'platform-team'

# Negative fixtures => expected message fragment.
$negativeCases = [ordered]@{
    'invalid-st1-root.vars.hcl'           = 'root_volume_type must be one of gp2, gp3, io1, io2'
    'invalid-io2-iops-ratio.vars.hcl'     = 'root_volume_iops out of range'
    'invalid-io1-missing-iops.vars.hcl'   = 'root_volume_iops is required for io1/io2'
    'invalid-gp2-with-iops.vars.hcl'      = 'must not be set for gp2'
    'invalid-throughput-not-gp3.vars.hcl' = 'root_volume_throughput is only valid for gp3'
    'invalid-no-protected.vars.hcl'       = 'At least one instance must set protected = true'
    'invalid-ami-format.vars.hcl'         = 'ami_id must look like'
}

$offlineOverride = @'
# GENERATED by scripts/task1-local-poc.ps1 - OFFLINE PLAN ONLY.
# Mock credentials, every AWS API call skipped. Git-ignored (*_override.tf)
# and deleted when the script ends. Never use for apply.
provider "aws" {
  access_key                  = "mock-access-key"
  secret_key                  = "mock-secret-key"
  allowed_account_ids         = []
  skip_credentials_validation = true
  skip_requesting_account_id  = true
  skip_metadata_api_check     = true
  skip_region_validation      = true
}
'@

$invalidLifecycle = @'
terraform {
  required_version = ">= 1.5.0, < 2.0.0"
}

variable "instances" {
  type    = map(object({ protected = bool }))
  default = { web03 = { protected = true } }
}

resource "terraform_data" "this" {
  for_each = var.instances
  input    = each.key

  lifecycle {
    prevent_destroy = each.value.protected
  }
}
'@

$tempRoot = Join-Path $env:TEMP ("task1-poc-" + [guid]::NewGuid().ToString('N').Substring(0, 8))
New-Item -ItemType Directory -Force -Path $tempRoot | Out-Null

try {
    # ------------------------------------------------------------------
    Write-Step '1. Baseline: validate-local.ps1'
    & powershell -NoProfile -ExecutionPolicy Bypass -File (Join-Path $PSScriptRoot 'validate-local.ps1') -PocLabel 'BASELINE' *>&1 |
        Select-String -Pattern '^(Repository structure|Required files|terraform (fmt|init|validate)|Secret/state check|Git repository)\s|BASELINE|missing' |
        ForEach-Object { Write-Host "  $_" }
    $results['Baseline (fmt/init/validate/hygiene)'] = ($LASTEXITCODE -eq 0)

    # ------------------------------------------------------------------
    Write-Step '2. Anti-pattern: prevent_destroy = each.value.protected must be rejected'
    $badDir = Join-Path $tempRoot 'invalid-lifecycle'
    New-Item -ItemType Directory -Force -Path $badDir | Out-Null
    [System.IO.File]::WriteAllText((Join-Path $badDir 'main.tf'), $invalidLifecycle)
    $r = Invoke-Terraform @("-chdir=$badDir", 'init', '-input=false', '-no-color')
    if ($r.Exit -eq 0) {
        $r = Invoke-Terraform @("-chdir=$badDir", 'validate', '-no-color')
    }
    $r.Text -split "`n" | Where-Object { $_ -match '^\s*Error: |prevent_destroy =' } | Select-Object -First 4 | ForEach-Object { Write-Host "  $($_.Trim())" -ForegroundColor DarkGray }
    $results['Dynamic prevent_destroy rejected'] = (Write-Check 'terraform refuses dynamic lifecycle value' ($r.Exit -ne 0))

    # ------------------------------------------------------------------
    Write-Step '3. Offline plan of account-a (mock credentials, no AWS calls)'
    [System.IO.File]::WriteAllText($overridePath, $offlineOverride)
    $planFile = Join-Path $tempRoot 'task1.tfplan'

    $r = Invoke-Terraform @('-chdir=account-a', 'init', '-backend=false', '-input=false', '-no-color')
    $planOk = ($r.Exit -eq 0)
    if ($planOk) {
        $r = Invoke-Terraform @('-chdir=account-a', 'plan', '-refresh=false', '-input=false', '-no-color', '-var-file=terraform.tfvars.example', "-out=$planFile")
        $planOk = ($r.Exit -eq 0)
        $r.Text -split "`n" | Where-Object { $_ -match 'will be created|^Plan:|Error' } | ForEach-Object { Write-Host "  $($_.Trim())" }
    }
    else {
        Write-Host $r.Text -ForegroundColor Red
    }

    $assertOk = $false
    if ($planOk) {
        $plan = (& terraform '-chdir=account-a' show -json $planFile | Out-String | ConvertFrom-Json)
        $changes = @($plan.resource_changes | Where-Object { $_.type -eq 'aws_instance' })
        $assertOk = $true

        $creates = @($changes | Where-Object { ($_.change.actions -join ',') -eq 'create' })
        $assertOk = (Write-Check 'exactly 5 aws_instance creates' ($creates.Count -eq 5 -and $changes.Count -eq 5) "($($creates.Count))") -and $assertOk

        $distinctKeys = @($changes | ForEach-Object { $_.change.after.key_name } | Sort-Object -Unique)
        $assertOk = (Write-Check 'five different key pairs' ($distinctKeys.Count -eq 5) "($($distinctKeys -join ', '))") -and $assertOk

        $distinctTypes = @($changes | ForEach-Object { $_.change.after.instance_type } | Sort-Object -Unique)
        $assertOk = (Write-Check 'five different instance types' ($distinctTypes.Count -eq 5)) -and $assertOk

        $provisioned = @($changes | Where-Object { @('io1', 'io2') -contains $_.change.after.root_block_device[0].volume_type })
        $assertOk = (Write-Check 'at least one io1/io2 root volume' ($provisioned.Count -ge 1) "($($provisioned.Count))") -and $assertOk

        foreach ($name in $expected.Keys) {
            $e = $expected[$name]
            $group = 'standard'
            if ($e.Protected) { $group = 'protected' }
            $address = "module.ec2.aws_instance.$group[`"$name`"]"
            $c = $changes | Where-Object { $_.address -eq $address }
            if (-not $c) {
                $assertOk = (Write-Check "$name planned at $address" $false) -and $assertOk
                continue
            }
            $a = $c.change.after
            $rbd = $a.root_block_device[0]
            $ok = ($a.instance_type -eq $e.Type) -and
                  ($rbd.volume_type -eq $e.Vol) -and
                  ([int]$rbd.volume_size -eq $e.Size) -and
                  (($null -eq $e.Iops) -or ([int]$rbd.iops -eq $e.Iops)) -and
                  (($null -eq $e.Tp) -or ([int]$rbd.throughput -eq $e.Tp)) -and
                  ($a.key_name -eq $e.Key) -and
                  ($a.tags.Name -eq $name) -and
                  ($a.tags.Environment -eq $e.Env) -and
                  ($a.tags.Owner -eq $expectedOwner) -and
                  ([bool]$a.disable_api_termination -eq $e.Protected) -and
                  ($rbd.encrypted -eq $true) -and
                  ($a.metadata_options[0].http_tokens -eq 'required')
            $detail = "{0} {1} {2}GB iops={3} key={4} Env={5} protected={6}" -f $a.instance_type, $rbd.volume_type, $rbd.volume_size, $rbd.iops, $a.key_name, $a.tags.Environment, $a.disable_api_termination
            $assertOk = (Write-Check "$name ($group)" $ok $detail) -and $assertOk
        }

        foreach ($outName in @('instance_ids', 'private_ips')) {
            $out = $plan.output_changes.$outName
            $keys = @()
            if ($out -and $out.after_unknown) {
                $keys = @($out.after_unknown.PSObject.Properties.Name | Sort-Object)
            }
            $ok = (($keys -join ',') -eq (($expected.Keys | Sort-Object) -join ','))
            $assertOk = (Write-Check "output $outName keyed by name" $ok "($($keys -join ', '))") -and $assertOk
        }
    }
    $results['Offline plan: 5 instances as specified'] = ($planOk -and $assertOk)

    # ------------------------------------------------------------------
    Write-Step '4. Negative input validation (must be rejected)'
    $negOk = $true
    foreach ($fixture in $negativeCases.Keys) {
        $fixturePath = Join-Path $repoRoot "tests\fixtures\task1\$fixture"
        $r = Invoke-Terraform @('-chdir=account-a', 'plan', '-refresh=false', '-input=false', '-no-color', "-var-file=$fixturePath")
        $flat = ($r.Text -replace '\s+', ' ')
        $ok = ($r.Exit -ne 0) -and ($flat -like "*$($negativeCases[$fixture])*")
        $negOk = (Write-Check $fixture $ok "-> '$($negativeCases[$fixture])'") -and $negOk
    }
    $results['Invalid volume/AMI/protection inputs rejected'] = $negOk
}
finally {
    if (Test-Path $overridePath) { Remove-Item -Force $overridePath }
}

try {
    # ------------------------------------------------------------------
    Write-Step '5. prevent_destroy mechanism demo (terraform_data, TEMP state, no AWS)'
    $demoDir = Join-Path $tempRoot 'prevent-destroy-demo'
    Copy-Item -Recurse (Join-Path $repoRoot 'tests\task1-prevent-destroy-demo') $demoDir
    $demoOk = $true

    $r = Invoke-Terraform @("-chdir=$demoDir", 'init', '-input=false', '-no-color')
    $demoOk = (Write-Check 'init' ($r.Exit -eq 0)) -and $demoOk

    $r = Invoke-Terraform @("-chdir=$demoDir", 'apply', '-auto-approve', '-input=false', '-no-color')
    $demoOk = (Write-Check 'apply creates 5 demo resources' ($r.Exit -eq 0 -and $r.Text -match '5 added')) -and $demoOk

    $withoutWeb01 = '-var=instances={web02={},web03={protected=true},web04={},web05={}}'
    $r = Invoke-Terraform @("-chdir=$demoDir", 'plan', '-input=false', '-no-color', $withoutWeb01)
    $demoOk = (Write-Check 'remove UNPROTECTED web01 -> plan allows destroy' ($r.Exit -eq 0 -and $r.Text -match '1 to destroy')) -and $demoOk

    $withoutWeb03 = '-var=instances={web01={},web02={},web04={},web05={}}'
    $r = Invoke-Terraform @("-chdir=$demoDir", 'plan', '-input=false', '-no-color', $withoutWeb03)
    $blocked = ($r.Exit -ne 0 -and $r.Text -match 'Instance cannot be destroyed')
    $demoOk = (Write-Check 'remove PROTECTED web03 -> plan rejected' $blocked) -and $demoOk
    $r.Text -split "`n" | Where-Object { $_ -match 'Error:|cannot be destroyed|terraform_data.protected' } | Select-Object -First 3 | ForEach-Object { Write-Host "      $($_.Trim())" -ForegroundColor DarkGray }

    $r = Invoke-Terraform @("-chdir=$demoDir", 'destroy', '-auto-approve', '-input=false', '-no-color')
    $destroyBlocked = ($r.Exit -ne 0 -and $r.Text -match 'Instance cannot be destroyed')
    $demoOk = (Write-Check 'terraform destroy -> rejected' $destroyBlocked) -and $demoOk

    $stateCount = @(& terraform "-chdir=$demoDir" state list).Count
    $demoOk = (Write-Check 'all 5 demo resources still in state after rejected destroy' ($stateCount -eq 5) "($stateCount)") -and $demoOk

    $results['prevent_destroy blocks protected destroy'] = $demoOk
}
finally {
    Remove-Item -Recurse -Force $tempRoot -ErrorAction SilentlyContinue
}

# ----------------------------------------------------------------------
Write-Host ''
Write-Host '==================== TASK 1 LOCAL POC SUMMARY ====================' -ForegroundColor Cyan
$allPassed = $true
foreach ($name in $results.Keys) {
    $passed = [bool]$results[$name]
    if (-not $passed) { $allPassed = $false }
    $label = 'FAIL'
    $color = 'Red'
    if ($passed) {
        $label = 'PASS'
        $color = 'Green'
    }
    Write-Host ('{0,-48} {1}' -f $name, $label) -ForegroundColor $color
}
Write-Host ''
if ($allPassed) {
    Write-Host 'POC-1 (LOCAL): PASS  (no AWS resources were created - real-AWS POC is in tests/task1-test.md)' -ForegroundColor Green
    exit 0
}
Write-Host 'POC-1 (LOCAL): FAIL' -ForegroundColor Red
exit 1
